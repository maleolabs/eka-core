// This file implements the snapshot repair path: the deterministic
// regeneration of the derived package aggregates (manifest.json,
// declarations.json, integrity.json) and the canonical re-serialization
// of unit.json entries, from the snapshot directory's units/ and
// attachments/ trees. It is the post-merge repair tool for LEGACY
// snapshots — layouts that still carry the aggregates (EKA < 0.10).
// Since ADR-027 the committed snapshot is SOURCE-ONLY (header.json,
// units/, attachments/ — no aggregates), so parallel merges never
// conflict on derived state and repair has nothing to rebuild; on a
// source-only snapshot it normalizes the unit.json entries and verifies
// the snapshot with the same per-unit verification a pull applies.
//
// Why it exists (the legacy merge story): a Git merge that combined two
// legacy snapshots is package-inconsistent BY CONSTRUCTION. The
// aggregates are whole-package projections (the manifest lists every
// unit, the integrity block carries every digest), so they change on
// both sides of any parallel knowledge change and Git reports a
// conflict; a line-wise merge of the two aggregate versions produces
// JSON that is usually well-formed but digest-inconsistent, which the
// next `eka sync pull` refuses (byte-exact verification, integrity
// failure class). The units/ tree, however, merges normally — every
// unit is its own file, and units changed on only one side merge
// cleanly. The correct merge result is therefore a REGENERATION of the
// aggregates from the merged units/ tree, exactly as a push would
// assemble them (exchange.EmitSource — the same serializer the push
// uses, so identical input produces byte-identical aggregates).
//
// Contract:
//
//   - header.json is the package contract and is NEVER rewritten: it
//     carries the identity facts (namespace, label, scope) — a changed
//     header is an identity change, which sync refuses, never silently
//     rewrites.
//   - content payloads and attachments are byte-exact knowledge and are
//     NEVER rewritten (lossless round-trip invariant).
//   - unit.json entries are re-serialized canonically (exchange.EmitSource
//     output): a no-op for canonical bytes, a normalization for legacy
//     key spellings or hand-edited metadata, so the per-unit digests
//     always match the bytes on disk.
//   - the derived aggregates are written ONLY when the snapshot already
//     carries them (a legacy layout); a source-only snapshot stays
//     source-only.
//   - every entry outside the known structure is rejected — the same
//     strictness as the package loader (RSF §9.5 reject-by-default).
//
// Failure contract: parsing/decoding errors abort BEFORE any write (a
// corrupt unit.json — e.g. an unresolved Git conflict marker — is
// refused and nothing is touched); the final self-consistency check
// runs the same verification as every pull
// (exchange.LoadPackageWithEntries). I/O failures mid-write can leave a
// partially rewritten snapshot (the aggregates are written last);
// re-running repair converges, and every subsequent `eka sync pull`
// still verifies byte-exact before seeding anything.

// snapshotAggregates are the derived package entries regenerated by
// RepairSnapshot — the entries a Git merge must never combine line-wise.
var snapshotAggregates = map[string]bool{
	"manifest.json":     true,
	"declarations.json": true,
	"integrity.json":    true,
}

// RepairSnapshot regenerates the derived aggregates and normalizes the
// unit.json entries of the snapshot directory at dir, in place, from
// the directory's units/ and attachments/ trees (see the file
// comment). header.json, content payloads and attachments are never
// touched. The snapshot is verified byte-exact
// (exchange.LoadPackageWithEntries) before the function returns.
func RepairSnapshot(dir string) error {
	// 1. Read every entry of the snapshot directory with the reader's
	// strictness: regular files only, no symlink following, entry names
	// inside the package root.
	entries, err := readSnapshotEntries(dir)
	if err != nil {
		return err
	}

	// 2. The header is the contract: required, parseable, and carrying
	// the package identity label. It is passed through unchanged into
	// the regenerated package (and never written back).
	headerData, ok := entries["header.json"]
	if !ok {
		return fmt.Errorf("snapshot repair refused: %s has no header.json entry: not an RSF snapshot", dir)
	}
	var header exchange.Header
	if err := json.Unmarshal(headerData, &header); err != nil {
		return fmt.Errorf("snapshot repair refused: cannot parse header.json: %w", err)
	}
	if header.PackageIdentityLabel == "" || header.ExportScope == "" {
		return fmt.Errorf("snapshot repair refused: header.json carries no package identity label or scope")
	}

	// 3. Group the unit entries: every units/<dir>/unit.json must be
	// paired with its units/<dir>/content payload. Both are required;
	// an orphan on either side is refused (an incomplete unit can never
	// be packaged consistently).
	unitJSONs := map[string][]byte{}
	contents := map[string][]byte{}
	var unitDirs []string
	for name, data := range entries {
		rest, ok := strings.CutPrefix(name, "units/")
		if !ok {
			continue
		}
		if uDir, ok := strings.CutSuffix(rest, "/unit.json"); ok {
			if _, dup := unitJSONs[uDir]; dup {
				return fmt.Errorf("snapshot repair refused: duplicate unit.json entry for %s", uDir)
			}
			unitJSONs[uDir] = data
			unitDirs = append(unitDirs, uDir)
		} else if strings.HasSuffix(rest, "/content") {
			uDir := strings.TrimSuffix(rest, "/content")
			contents[uDir] = data
		} else {
			return fmt.Errorf("snapshot repair refused: unknown entry %s under units/", name)
		}
	}
	for _, uDir := range unitDirs {
		if _, ok := contents[uDir]; !ok {
			return fmt.Errorf("snapshot repair refused: unit %s has no content entry", uDir)
		}
	}
	for uDir := range contents {
		if _, ok := unitJSONs[uDir]; !ok {
			return fmt.Errorf("snapshot repair refused: content entry %s has no unit.json entry", uDir)
		}
	}
	sort.Strings(unitDirs)

	// 4. Decode every unit from its canonical bytes (legacy key
	// spellings normalize through DecodeUnit, the same pass the package
	// loader applies). The decode is strict: an unresolved Git conflict
	// marker in a unit.json refuses the whole repair, before any write.
	units := make([]*exchange.Unit, 0, len(unitDirs))
	for _, uDir := range unitDirs {
		u, err := exchange.DecodeUnit(unitJSONs[uDir], contents[uDir])
		if err != nil {
			return fmt.Errorf("snapshot repair refused: cannot decode %s/unit.json: %w", uDir, err)
		}
		units = append(units, u)
	}

	// 5. Attachments are carried verbatim, keyed by their package IDs.
	var attachments []*exchange.Attachment
	for name, data := range entries {
		id, ok := strings.CutPrefix(name, "attachments/")
		if !ok {
			continue
		}
		attachments = append(attachments, &exchange.Attachment{ID: id, Data: data})
	}
	sort.Slice(attachments, func(i, j int) bool { return attachments[i].ID < attachments[j].ID })

	// 6. Assemble and emit exactly like a push: the merged units/ tree
	// is the authority; external references are re-detected with the
	// push's detection (declarations.json is derived state).
	unitSet := make(map[string]bool, len(units))
	for _, u := range units {
		unitSet[u.CanonicalIdentityForm] = true
	}
	pkg := &exchange.Package{
		Header: header,
		Units:  units,
		Declarations: exchange.Declarations{
			Closure:            exchange.ClosureDeclaration{Scope: header.ExportScope, Seeds: []string{}},
			ExternalReferences: detectExternals(units, unitSet),
			Extensions:         []exchange.ExtensionDecl{},
		},
		Attachments: attachments,
	}
	// 6b. Emit: a legacy snapshot (aggregates present) gets the full
	// package projection so the regenerated aggregates land back on
	// disk; a source-only snapshot gets the source projection (the
	// aggregates stay out of the repository).
	legacy := entries["manifest.json"] != nil
	var files []exchange.EmittedFile
	if legacy {
		files, err = exchange.Emit(pkg)
	} else {
		files, _, err = exchange.EmitSource(pkg)
	}
	if err != nil {
		return fmt.Errorf("snapshot repair failed: %w", err)
	}

	// 7. Write: the canonical unit.json entries always; the derived
	// aggregates ONLY when the snapshot already carries them (a legacy
	// layout — since ADR-027 the committed snapshot is source-only and
	// the aggregates stay out of the repository). Content payloads,
	// attachments and header.json are never written (their bytes are
	// the authority, see the file comment).
	for _, f := range files {
		switch {
		case snapshotAggregates[f.Name]:
			if !legacy {
				continue // source-only snapshot: aggregates stay uncommitted.
			}
			// Aggregates land at the snapshot root.
			if err := os.WriteFile(filepath.Join(dir, f.Name), f.Data, 0o644); err != nil {
				return fmt.Errorf("snapshot repair failed: cannot write %s: %w", f.Name, err)
			}
		case strings.HasPrefix(f.Name, "units/") && strings.HasSuffix(f.Name, "/unit.json"):
			path := filepath.Join(dir, filepath.FromSlash(f.Name))
			if err := os.WriteFile(path, f.Data, 0o644); err != nil {
				return fmt.Errorf("snapshot repair failed: cannot write %s: %w", f.Name, err)
			}
		}
	}

	// 8. Verify the regenerated snapshot with the same verification
	// every pull applies (legacy: byte-exact package; source-only:
	// structural + per-unit), so a repaired snapshot is guaranteed
	// seedable.
	if _, err := exchange.LoadSnapshot(dir); err != nil {
		return fmt.Errorf("snapshot repair failed: regenerated snapshot refused: %w", err)
	}
	return nil
}

// readSnapshotEntries reads every regular file of the snapshot directory
// as an entry keyed by its forward-slash root-relative name, mirroring
// the package reader's strictness: symlinks are never followed (an entry
// must be a regular file) and every entry name must stay inside the
// package root (no "..", no absolute paths, no Windows separators — the
// writer's entry-name contract, defense in depth; the walk starts inside
// the snapshot root, so a relative path can never escape it).
func readSnapshotEntries(dir string) (map[string][]byte, error) {
	entries := map[string][]byte{}
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		if d.Type()&os.ModeSymlink != 0 {
			return nil
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		name := filepath.ToSlash(rel)
		if err := snapshotEntryNameSafe(name); err != nil {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("snapshot repair refused: cannot read %s: %w", name, err)
		}
		entries[name] = data
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("snapshot repair refused: cannot read the snapshot: %w", err)
	}
	return entries, nil
}

// snapshotEntryNameSafe mirrors the package writer's entry-name contract
// (exchange.checkEntryName) on the repair side — the same defense the
// reader applies to every opened package. Entry names that could escape
// the package root are refused.
func snapshotEntryNameSafe(name string) error {
	switch {
	case name == "":
		return fmt.Errorf("snapshot repair refused: empty entry name")
	case name == "." || name == ".." || strings.HasPrefix(name, "/") ||
		strings.Contains(name, "..") || strings.Contains(name, "\\") ||
		strings.Contains(name, ":"):
		return fmt.Errorf("snapshot repair refused: entry name %q is not allowed (must not contain '..', start with '/', or contain '\\' or ':')", name)
	}
	return nil
}
